import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/lib/stepProposalReview.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
vm.runInNewContext(compiled, { exports, require: () => { throw Error('Unexpected runtime dependency'); } });
const review = exports.reviewStepProposals;
const base = { featureId: 'hole-1', toolId: 't1', toolName: 'Bohrer', method: 'drill',
  status: 'conditional', diameterMm: 8, depthMm: 12, spindleRpm: 3000, feedMmMin: 120 };
const drill = review([base]);
assert.equal(drill.length, 1);
assert.equal(drill[0].status, 'requires-review');
assert.equal(drill[0].checks.length, 5);
assert.ok(drill[0].checks.every(check => check.status === 'open'));
assert.ok(drill[0].checks.some(check => check.label === 'Bohrvorgang'));
const helix = review([{ ...base, method: 'helical-mill', toolId: 'mill-6', toolName: 'Schaftfräser' }]);
assert.equal(helix.length, 1);
assert.equal(helix[0].method, 'helical-mill');
assert.equal(helix[0].status, 'requires-review');
assert.equal(helix[0].checks.length, 5);
assert.ok(helix[0].checks.every(check => check.status === 'open'));
assert.ok(helix[0].checks.some(check => check.label === 'Helix-Eintritt'));
assert.ok(!helix[0].checks.some(check => check.label === 'Bohrvorgang'));
assert.equal(review([{ ...base, status: 'ready' }]).length, 0);
assert.equal(review([{ ...base, feedMmMin: NaN }]).length, 0);
assert.equal(review([base, base]).length, 1);
const unnamed = review([{ ...base, toolId: 'unnamed', toolName: '' }, base]);
assert.equal(unnamed.length, 2);
assert.equal(unnamed[0].status, 'requires-review');
assert.ok(unnamed[0].checks.every(check => check.status === 'open'));
assert.ok(unnamed[0].checks.some(check => check.label === 'Werkzeugbezeichnung'));
assert.equal(unnamed[1].checks.length, 5);
assert.equal(review([base, { ...base, toolId: 'invalid', feedMmMin: 0 }]).length, 0);
assert.equal(review(null).length, 0);
const app = fs.readFileSync(new URL('../src/App.svelte', import.meta.url), 'utf8');
const panel = fs.readFileSync(new URL('../src/lib/StepAdvisorPanel.svelte', import.meta.url), 'utf8');
assert.match(app, /reviewStepProposals\(advisorOperationProposals\)/);
assert.match(app, /proposalReviews=\{advisorProposalReviews\}/);
assert.match(panel, /Prüfstatus:/);
assert.match(panel, /check\.reason/);
console.log('011-F4 proposal review checklist PASS');
