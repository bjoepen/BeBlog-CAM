import fs from 'node:fs';
import ts from 'typescript';
const fail=m=>{throw new Error(`006B contract FAIL: ${m}`)};
const source=fs.readFileSync('src/lib/dxfMultiTargetSelection.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const mod=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const normalized=mod.normalizeDxfTargetIds({contourId:4,contourIds:[7,2,7,4]});
if(normalized.join(',')!=='2,4,7')fail('target ids must be unique and stable');
if(mod.normalizeDxfTargetIds({contourId:5}).join(',')!=='5')fail('legacy singular contourId must remain supported');
if(mod.toggleDxfTargetId({contourId:2,contourIds:[2,4]},4).join(',')!=='2')fail('toggle must remove an existing target');
if(mod.toggleDxfTargetId({contourId:2,contourIds:[2]},6).join(',')!=='2,6')fail('toggle must add a target');
if(mod.dxfMultiTargetKey([6,2,6])!=='dxf-contours:2,6')fail('multi target key must be deterministic');
const aggregate=fs.readFileSync('src/lib/dxfMultiTargetToolpath.ts','utf8');
if(!aggregate.includes('runs:toolpaths.flatMap(path=>path.runs)'))fail('canonical target runs must be aggregated before safe motion');
if(!aggregate.includes('motions:undefined'))fail('aggregate must not concatenate already-materialized machine motions');
if(!aggregate.includes('Restmaterial mit DXF-Mehrfachauswahl'))fail('multi-target rest machining must fail closed in 006B');
const active=fs.readFileSync('src/lib/activeCanonicalToolpath.ts','utf8');
if(!active.includes('buildDxfMultiTargetContourState')||!active.includes('buildDxfMultiTargetPocketState'))fail('Bearbeiten must consume multi-target canonical truth');
const preflight=fs.readFileSync('src/lib/jobPreflight.ts','utf8');
if(!preflight.includes('buildDxfMultiTargetContourState')||!preflight.includes('buildDxfMultiTargetPocketState'))fail('Prüfen must consume the same multi-target canonical truth');
const app=fs.readFileSync('src/App.svelte','utf8');
if(!app.includes('toggleDxfTargetId(operation,id)'))fail('DXF viewport selection must toggle targets');
if(!app.includes("importSummary?.kind!=='dxf'||(operation.kind==='contour'&&operation.topology==='open')"))fail('STEP/open contour selection must retain single-target semantics');
console.log('006B contract PASS: DXF contour/pocket multi-target selection aggregates at Canonical Toolpath level; STEP remains unchanged; 004T materializes transitions afterwards.');
