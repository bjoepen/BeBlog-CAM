import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import { compile } from 'svelte/compiler';
const panel = fs.readFileSync(new URL('../src/lib/StepAdvisorPanel.svelte', import.meta.url), 'utf8');
const compiled = compile(panel, { filename: 'StepAdvisorPanel.svelte', generate: 'client' });
assert.ok(compiled.js.code.length > 0);
assert.match(panel, /aria-expanded=\{expandedFeatureIds\.includes\(feature\.featureId\)\}/);
assert.match(panel, /onclick=\{\(\) => toggleFeature\(feature\.featureId\)\}/);
assert.match(panel, /\{#if expandedFeatureIds\.includes\(feature\.featureId\)\}/);
assert.match(panel, /expandedFeatureIds = toggleExpandedFeature\(expandedFeatureIds, id\)/);
assert.match(panel, /proposalReviews\.filter/);
assert.match(panel, /Keine Bearbeitung wird erzeugt/);
const source = fs.readFileSync(new URL('../src/lib/stepAdvisorDisclosure.ts', import.meta.url), 'utf8');
const transpiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
vm.runInNewContext(transpiled, { exports });
const toggle = exports.toggleExpandedFeature;
let cards = [];
cards = toggle(cards, 'hole-1');
assert.deepEqual(Array.from(cards), ['hole-1'], 'first card must open');
cards = toggle(cards, 'hole-2');
assert.deepEqual(Array.from(cards), ['hole-1', 'hole-2'], 'second card must not close first');
cards = toggle(cards, 'hole-1');
assert.deepEqual(Array.from(cards), ['hole-2'], 'closing first must preserve second');
cards = toggle(cards, 'hole-2');
assert.deepEqual(Array.from(cards), [], 'both cards must close');
console.log('011-F5 visual STEP advisor disclosure PASS');
